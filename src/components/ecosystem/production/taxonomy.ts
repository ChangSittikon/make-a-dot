export type BudgetLevel = 0 | 1 | 2;
export type StyleCode = 'H' | 'S' | 'V' | 'C';

export interface TaxProduct {
  name: string;
  level: BudgetLevel;
  styles: StyleCode[];
  seedId?: string;
}
export interface TaxSub {
  name: string;
  products: TaxProduct[];
}
export interface TaxSector {
  id: string; // '01'..'12'
  industryId: string; // 'ind_01'..
  name: string;
  subs: TaxSub[];
}

const P = (s: string): TaxProduct => {
  const [name, level, styles, seedId] = s.split('|');
  return {
    name,
    level: (Number(level) || 0) as BudgetLevel,
    styles: (styles || '').split('').filter(Boolean) as StyleCode[],
    seedId: seedId || undefined,
  };
};
const SUB = (name: string, products: string[]): TaxSub => ({ name, products: products.map(P) });

