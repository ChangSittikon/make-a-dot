export function detectSector(name: string, hint?: string): string {
  const t = name.toLowerCase();
  const exact = ALL_TAX_PRODUCTS.find((x) => x.product.name.toLowerCase() === t.trim());
  if (exact) return exact.sector.id;
  let best = '';
  let bestScore = 0;
  for (const [id, words] of Object.entries(KEYWORDS)) {
    const s = words.reduce((acc, w) => (t.includes(w) ? acc + w.length : acc), 0);
    if (s > bestScore) {
      bestScore = s;
      best = id;
    }
  }
  return best || hint || '10';
}

