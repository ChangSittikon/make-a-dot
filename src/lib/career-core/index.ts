/**
 * คำนวณมูลค่าทุนชีวิตแฝง (Hidden Nodes Valuation) ตามรายการที่ผู้ใช้เลือก
 */
export function calculateHiddenNodesValuation(
  selectedNodeIds: string[]
): HiddenValuationResult {
  let sweatThb = 0;
  let equipThb = 0;
  let venueThb = 0;
  let ipThb = 0;
  const unlockedOpps: string[] = [];

  selectedNodeIds.forEach((id) => {
    const item = HIDDEN_NODES_CATALOG.find((n) => n.id === id);
    if (!item) return;

    if (item.equityType === 'sweat') sweatThb += item.baseEstimatedValuationThb;
    else if (item.equityType === 'equip') equipThb += item.baseEstimatedValuationThb;
    else if (item.equityType === 'venue') venueThb += item.baseEstimatedValuationThb;
    else if (item.equityType === 'ip') ipThb += item.baseEstimatedValuationThb;

    unlockedOpps.push(item.suggestedAction);
  });

  const total = sweatThb + equipThb + venueThb + ipThb;

  const capTableSuggestionText =
    total > 0
      ? `คุณมีทุนชีวิตแฝงรวมมูลค่า ฿${total.toLocaleString()} สามารถโอนไปเป็นสัดส่วนหุ้น Sweat Equity (฿${sweatThb.toLocaleString()}), Equip (฿${equipThb.toLocaleString()}), และ Venue (฿${venueThb.toLocaleString()}) ในตารางหุ้นทันทีโดยไม่ต้องใช้เงินสดก้อนใหญ่!`
      : 'กรุณาเลือกทุนชีวิตรอบตัวอย่างน้อย 1 รายการเพื่อเริ่มสแกนขุมทรัพย์แฝง';

  return {
    totalEstimatedValuationThb: total,
    breakdown: {
      sweatThb,
      equipThb,
      venueThb,
      ipThb,
    },
    selectedCount: selectedNodeIds.length,
    unlockedOpportunities: unlockedOpps,
    capTableSuggestionText,
  };
}

